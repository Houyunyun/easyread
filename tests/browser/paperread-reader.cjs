// Run in a disposable paper library after loading a reader page.
async page => {
  const check = (ok, message) => { if (!ok) throw new Error(message); };
  const live = field => page.evaluate(field => Object.values(PR.state.reader[field] || {}).filter(x => !x.deleted).length, field);
  const beforeInk = await live('ink'), beforeStickers = await live('stickers');
  const paragraph = page.locator('#paper > .blk-para').first();
  await paragraph.scrollIntoViewIfNeeded();
  const rect = await paragraph.boundingBox();
  const start = {x:rect.x + 30, y:rect.y + 20};
  await page.locator('#inkToggle').click();
  await page.mouse.move(start.x, start.y); await page.mouse.down();
  await page.mouse.move(start.x + 65, start.y + 12, {steps:8}); await page.mouse.up();
  check(await live('ink') === beforeInk + 1, 'Pointer drawing did not create a stroke');
  await page.locator('[data-ink-erase]').click();
  await page.mouse.move(start.x + 20, start.y + 3); await page.mouse.down();
  await page.mouse.move(start.x + 55, start.y + 10, {steps:4}); await page.mouse.up();
  check(await live('ink') === beforeInk, 'Eraser did not remove the intersected stroke');
  await page.locator('[data-ink-undo]').click();
  check(await live('ink') === beforeInk + 1, 'Eraser undo did not restore the stroke');
  await page.locator('[data-ink-redo]').click();
  check(await live('ink') === beforeInk, 'Eraser redo failed');
  await page.locator('[data-ink-undo]').click();
  await page.locator('#stickerToggle').click();
  await page.locator('[data-asset="atom"]').dblclick();
  await page.waitForFunction(n => Object.values(PR.state.reader.stickers || {}).filter(x => !x.deleted).length === n + 1, beforeStickers);
  await page.locator('#stickerToggle').click();
  await page.locator('[data-ink-text]').click();
  await page.mouse.click(start.x + 100, start.y + 15);
  await page.locator('.ink-text-editor').fill('Reader text box\n$E=mc^2$');
  await page.locator('.ink-text-editor').press('ControlOrMeta+Enter');
  check(await live('stickers') === beforeStickers + 2, 'Text box did not save');
  await page.locator('[data-ink-lasso]').click();
  const bounds = await page.evaluate(() => {
    const rects = [...document.querySelectorAll('#inkLayer path[data-stroke], #inkLayer [data-sticker-content]')].map(el => el.getBoundingClientRect());
    return {left:Math.min(...rects.map(r=>r.left))-15, right:Math.max(...rects.map(r=>r.right))+15,
      top:Math.min(...rects.map(r=>r.top))-15, bottom:Math.max(...rects.map(r=>r.bottom))+15};
  });
  await page.mouse.move(bounds.left,bounds.top); await page.mouse.down();
  for (const [x,y] of [[bounds.right,bounds.top],[bounds.right,bounds.bottom],[bounds.left,bounds.bottom],[bounds.left,bounds.top]]) await page.mouse.move(x,y,{steps:8});
  await page.mouse.up();
  await page.locator('#stickerTools [data-action="group"]').click();
  check(await page.evaluate(() => {
    const content = [...Object.values(PR.state.reader.ink), ...Object.values(PR.state.reader.stickers)].filter(x=>!x.deleted);
    return content.length>=3 && content.every(x=>x.groupId && x.groupId===content[0].groupId);
  }), 'Lasso grouping did not save the mixed drawing selection');
  await page.keyboard.press('Escape');
  await page.evaluate(() => PR.flushPending());
  await page.reload();
  await page.waitForFunction(() => !!PR.state.paper && !!document.querySelector('#paper > .blk'));
  check(await live('ink') === beforeInk + 1, 'Ink lost on reload');
  check(await live('stickers') === beforeStickers + 2, 'Sticker/text lost on reload');

  await page.locator('[data-act="research"]').click();
  await page.locator('#rp-map-expand').click();
  await page.locator('[data-map-edit="toggle"]').click();
  const node = page.locator('#mindmapDlg me-tpc').filter({hasText:'Method'}).first();
  await page.waitForTimeout(100);
  await node.click();
  await page.locator('[data-map-edit=rename]').click();
  const input = page.locator('#mindmapDlg #input-box');
  await input.fill('Edited method $x^2$');
  await input.press('Enter');
  await page.waitForFunction(() => PR.state.mindmap?.mermaid.includes('Edited method'));
  await page.waitForFunction(() => document.querySelector('.mm-edit-status')?.textContent === PR.t('已保存'));
  await page.keyboard.press('Escape');
  await page.reload();
  await page.waitForFunction(() => !!PR.state.paper);
  await page.locator('[data-act="research"]').click();
  await page.waitForFunction(() => document.querySelector('#rp-mindmap')?.textContent.includes('Edited method'));
  await page.locator('#rp-deep-expand').click();
  check(await page.locator('#deepReportDlg').isVisible(), 'Deep report did not open');
  await page.keyboard.press('Escape');
  await page.evaluate(() => PR.openPaperNote());
  await page.locator('[data-np="notes"]').click();
  await page.locator('[data-np-act="smart"]').click();
  await page.locator('[data-smart-start]').click();
  await page.locator('.smart-card [data-smart-action="accept"]').click();
  await page.waitForFunction(() => !document.querySelector('.smart-card'));
  check(await page.evaluate(() => PR.myNotes().some(note=>note.ai_generated)), 'Accepted smart suggestion was not applied');
  await page.locator('[data-np="paper"]').click();
  await page.locator('[data-note-mode="source"]').click();
  await page.locator('#paperNote').fill('# Workspace\n\nPersistent note');
  await page.locator('[data-note-expand]').click();
  await page.locator('[data-note-layout="stack"]').click();
  await page.keyboard.press('Escape');
  await page.evaluate(() => PR.finishPanelNote());
  check(await page.evaluate(() => PR.state.reader.paper_note.body.includes('Persistent note')), 'Workspace note lost');
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(() => PR.openSide(null));
  await page.waitForTimeout(300);
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Narrow reader overflows horizontally');
  return {drawing:true, eraserUndoRedo:true, lassoGrouping:true, stickerAndTextPersist:true, editableMindmapPersists:true, deepReport:true, smartAnnotations:true, noteWorkspace:true, narrowLayout:true};
}
